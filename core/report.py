def _badge(sev: str) -> str:
    col = SEVERITY_COLOR.get(sev, "#8B8B8B")
    return f'<span class="badge" style="background:{col};color:#080808">{html.escape(sev.upper())}</span>'


def render_html(result: Dict[str, Any], printable: bool = False) -> str:
    module = html.escape(str(result.get("module", "scan")))
    target = html.escape(str(result.get("target", "")))
    risk = str(result.get("risk", "info")).lower()
    score = int(result.get("score") or 0)
    findings = _sorted_findings(result.get("findings"))

    rows = "".join(
        f"<tr><td>{_badge(str(item.get('severity', 'info')).lower())}</td>"
        f"<td>{html.escape(str(item.get('title', '')))}</td>"
        f"<td>{html.escape(str(item.get('detail', '')))}</td></tr>"
        for item in findings
    )
    findings_table = (
        "<table><thead><tr><th>Severity</th><th>Finding</th><th>Detail</th></tr></thead>"
        f"<tbody>{rows}</tbody></table>"
        if findings
        else "<p style='color:#9A9A9A'>No findings produced by this module.</p>"
    )

    data_blocks: List[str] = []
    for key, value in result.items():
        if key in ("findings", "module", "target", "summary", "risk", "score", "ok", "error", "message"):
            continue
        if isinstance(value, (dict, list)) and value:
            payload = html.escape(json.dumps(value, indent=2, default=str)[:8000])
            data_blocks.append(f"<div class='card'><h2>{html.escape(str(key))}</h2><pre>{payload}</pre></div>")
        elif value not in (None, "", [], {}):
            data_blocks.append(
                f"<div class='card'><h2>{html.escape(str(key))}</h2>"
                f"<div class='kv'><dt>value</dt><dd>{html.escape(str(value))}</dd></div></div>"
            )

    status_block = ""
    if not result.get("ok"):
        status_block = (
            f"<div class='card'><h2>failure</h2>"
            f"<div class='note'><strong>{html.escape(str(result.get('error')))}</strong><br>"
            f"{html.escape(str(result.get('message', '')))}</div></div>"
        )

    print_note = (
        "<div class='note'>Save as PDF with your browser's print dialog "
        "(Ctrl+P → Destination: Save as PDF). This file is self-contained: no "
        "external fonts, scripts or images are loaded.</div>"
        if printable
        else ""
    )

    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>KING REAPER X — {module} — {target}</title>
<style>{BASE_CSS}</style></head>
<body><div class="wrap">
<header>
  <h1>KING <span>REAPER</span> X</h1>
  <div class="meta">
    Module: <strong>{module}</strong> &nbsp;·&nbsp; Target: <strong>{target}</strong><br>
    Generated {html.escape(str(result.get('finished') or now_iso()))} &nbsp;·&nbsp; Framework v{VERSION}<br>
    Overall risk {_badge(risk)} &nbsp;·&nbsp; Score {score}/100
  </div>
</header>
{print_note}
<div class="card"><h2>summary</h2>
  <div style="display:flex;gap:28px;align-items:center;flex-wrap:wrap">
    <div><div class="score" style="color:{SEVERITY_COLOR.get(risk,'#fff')}">{score}</div>
         <div style="color:#9A9A9A;font-size:11px">{len(findings)} finding(s)</div></div>
    <div style="flex:1;min-width:240px">{html.escape(str(result.get('summary', '')))}</div>
  </div>
</div>
<div class="card"><h2>findings</h2>{findings_table}</div>
{status_block}
{''.join(data_blocks)}
<footer>
  Generated by KING REAPER X v{VERSION}. All collection uses public, authorized or
  explicitly consented sources. IP geolocation resolves a network edge, not a person.
  Findings are advisory: verify before acting.
</footer>
</div></body></html>"""


def write_html(result: Dict[str, Any], path: Optional[Path] = None, printable: bool = False) -> Path:
    ensure_dirs()
    suffix = "_print" if printable else ""
    target = Path(path) if path else REPORT_DIR / f"{_stem(result.get('target', 'target'), result.get('module', 'scan'))}{suffix}.html"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_html(result, printable=printable), encoding="utf-8")
    return target


def write_all(result: Dict[str, Any], stem_dir: Optional[Path] = None) -> Dict[str, str]:
    """Write json + md + html + print-html. Returns the paths by format."""
    ensure_dirs()
    base = _stem(result.get("target", "target"), result.get("module", "scan"))
    directory = Path(stem_dir) if stem_dir else REPORT_DIR
    directory.mkdir(parents=True, exist_ok=True)
    return {
        "json": str(write_json(result, directory / f"{base}.json")),
        "markdown": str(write_markdown(result, directory / f"{base}.md")),
        "html": str(write_html(result, directory / f"{base}.html")),
        "print_html": str(write_html(result, directory / f"{base}_print.html", printable=True)),
        "pdf_note": "Print the *_print.html file in a browser and choose 'Save as PDF'.",
    }


def write_bundle(results: List[Dict[str, Any]], title: str = "assessment", directory: Optional[Path] = None) -> Dict[str, str]:
    """One report covering several module runs (used by `reaper audit`)."""
    ensure_dirs()
    directory = Path(directory) if directory else REPORT_DIR
    directory.mkdir(parents=True, exist_ok=True)
    stamp = now_iso().replace(":", "").replace("-", "")
    base = f"bundle_{title}_{stamp}"
    bundle = {
        "ok": all(item.get("ok") for item in results),
        "module": "bundle",
        "target": title,
        "finished": now_iso(),
        "findings": [finding for item in results for finding in (item.get("findings") or [])],
        "risk": _worst(results),
        "score": min(100, sum(int(item.get("score") or 0) for item in results)),
        "summary": f"{len(results)} module(s), "
        f"{sum(len(item.get('findings') or []) for item in results)} finding(s)",
        "runs": results,
    }
    paths = write_all(bundle, directory)
    return paths


def _worst(results: List[Dict[str, Any]]) -> str:
    order = {"critical": 4, "high": 3, "medium": 2, "low": 1, "info": 0}
    worst = max((order.get(str(item.get("risk", "info")).lower(), 0) for item in results), default=0)
    return {4: "critical", 3: "high", 2: "medium", 1: "low", 0: "info"}[worst]
