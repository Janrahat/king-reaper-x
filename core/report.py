"""Report generation: JSON, Markdown, HTML, and a self-contained printable HTML.

There is no PDF library in the standard library. Instead of shipping a fake
"PDF" button, :func:`render_print_html` produces a paginated, print-styled HTML
document that browsers save as PDF via ``Ctrl+P`` — and the CLI says exactly that.
"""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

from core.config import REPORT_DIR, VERSION, ensure_dirs
from core.utils import now_iso

SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}

SEVERITY_COLOR = {
    "critical": "#FF1010",
    "high": "#FF4D4D",
    "medium": "#FFA500",
    "low": "#FFD700",
    "info": "#8B8B8B",
}


def _stem(target: str, module: str) -> str:
    safe = "".join(ch if ch.isalnum() or ch in "-._" else "_" for ch in str(target or "target"))
    return f"{module}_{safe}_{now_iso().replace(':', '').replace('-', '')}"


def _sorted_findings(findings: Iterable[Dict[str, Any]]) -> List[Dict[str, Any]]:
    return sorted(
        list(findings or []),
        key=lambda item: (SEVERITY_ORDER.get(str(item.get("severity", "info")).lower(), 9), str(item.get("title", ""))),
    )


def write_json(result: Dict[str, Any], path: Optional[Path] = None) -> Path:
    ensure_dirs()
    target = Path(path) if path else REPORT_DIR / f"{_stem(result.get('target', 'target'), result.get('module', 'scan'))}.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(result, indent=2, default=str, ensure_ascii=False) + "\n", encoding="utf-8")
    return target


def render_markdown(result: Dict[str, Any]) -> str:
    lines: List[str] = []
    module = result.get("module", "scan")
    target = result.get("target", "")
    lines.append(f"# KING REAPER X — {module} report")
    lines.append("")
    lines.append(f"**Target:** `{target}`  ")
    lines.append(f"**Generated:** {result.get('finished') or now_iso()}  ")
    lines.append(f"**Framework:** v{VERSION}  ")
    lines.append(f"**Risk:** {result.get('risk', 'info').upper()} (score {result.get('score', 0)}/100)")
    lines.append("")
    if result.get("summary"):
        lines.append(f"> {result['summary']}")
        lines.append("")
    if not result.get("ok"):
        lines.append(f"**Result:** failed — `{result.get('error')}`: {result.get('message', '')}")
        lines.append("")
        return "\n".join(lines)

    findings = _sorted_findings(result.get("findings"))
    lines.append(f"## Findings ({len(findings)})")
    lines.append("")
    if not findings:
        lines.append("No findings were produced by this module.")
    else:
        lines.append("| Severity | Title | Detail |")
        lines.append("|---|---|---|")
        for item in findings:
            detail = str(item.get("detail", "")).replace("\n", " ").replace("|", "\\|")[:300]
            title = str(item.get("title", "")).replace("|", "\\|")[:140]
            lines.append(f"| {str(item.get('severity', 'info')).upper()} | {title} | {detail} |")
    lines.append("")

    lines.append("## Module data")
    lines.append("")
    for key, value in result.items():
        if key in ("findings", "module", "target", "summary", "risk", "score", "ok", "error", "message"):
            continue
        if isinstance(value, (dict, list)) and value:
            lines.append(f"### {key}")
            lines.append("```json")
            lines.append(json.dumps(value, indent=2, default=str)[:6000])
            lines.append("```")
            lines.append("")
        elif value not in (None, "", [], {}):
            lines.append(f"- **{key}:** {value}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Generated by KING REAPER X. Collection uses public, authorized or consented sources only.")
    return "\n".join(lines)


def write_markdown(result: Dict[str, Any], path: Optional[Path] = None) -> Path:
    ensure_dirs()
    target = Path(path) if path else REPORT_DIR / f"{_stem(result.get('target', 'target'), result.get('module', 'scan'))}.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_markdown(result), encoding="utf-8")
    return target


