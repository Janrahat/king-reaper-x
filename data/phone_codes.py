#: Dialling codes sorted longest-first so "1" never shadows "123".
SORTED_CODES = sorted(COUNTRIES, key=len, reverse=True)


def lookup_calling_code(code: str) -> Optional[Tuple[str, str, str]]:
    """Return ``(iso, name, dial)`` for a calling code."""
    return COUNTRIES.get(str(code).strip().lstrip("+"))


def split_international(number: str) -> Tuple[Optional[str], Optional[str]]:
    """Split an E.164 number into ``(calling_code, national_number)``.

    Returns ``(None, None)`` when no assigned calling code matches.
    """
    digits = "".join(ch for ch in str(number or "") if ch.isdigit())
    if not digits:
        return None, None
    for code in SORTED_CODES:
        if digits.startswith(code):
            national = digits[len(code):]
            if not national:
                continue
            # "1" is a valid match even for NANP territories (1-242 Bahamas):
            # the area code is resolved afterwards by :func:`resolve_nanp`.
            return code, national
    return None, None


def resolve_nanp(national: str) -> Optional[Tuple[str, str]]:
    """Map a NANP national number to ``(iso, country_name)`` when possible."""
    digits = "".join(ch for ch in str(national or "") if ch.isdigit())
    if len(digits) >= 3 and digits[:3] in NANP:
        return NANP[digits[:3]]
    return ("US", "United States")


def length_hint(code: str) -> Optional[Tuple[int, int]]:
    return LENGTH_HINTS.get(str(code))
